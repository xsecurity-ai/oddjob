func TestBlockedNeedsAProductAndAStatus(t *testing.T) {
	cf := http.Header{"Cf-Ray": {"8a1b2c3d4e5f6789-LHR"}}
	cases := []struct {
		name   string
		status int
		h      http.Header
		body   string
		want   string
	}{
		// The whole point. A 403 on /admin is the application
		// telling a tester where the boundary is, and calling it a
		// WAF block would hide a real access-control finding behind
		// a plausible excuse.
		{"a bare 403 is the server's answer, not a block",
			403, nil, "<h1>Forbidden</h1>", ""},
		{"a 200 is never a block however it is branded",
			200, cf, "ray id: abc", ""},
		// 401 is the server saying what to do next.
		{"a 401 is authentication, not interdiction",
			401, cf, "attention required! | cloudflare", ""},

		{"a cf-ray header on a 403 is Cloudflare",
			403, cf, "", "Cloudflare"},
		{"...and on a 503, which is the mode that looks like downtime",
			503, cf, "", "Cloudflare"},
		{"...and on a 429",
			429, cf, "", "Cloudflare"},
		{"Cloudflare's own wording counts without the header",
			403, nil, "<title>Attention Required! | Cloudflare</title>",
			"Cloudflare"},
		// NOT a block. `Server: cloudflare` is on everything
		// Cloudflare proxies, so a legitimate 403 from the origin
		// behind it carries the header too -- and excusing a real
		// access-control boundary as "the CDN blocked us" is worse
		// than inventing a finding. cf-ray is what means Cloudflare
		// itself decided.
		{"Server: cloudflare alone is the proxy, not a decision",
			403, http.Header{"Server": {"cloudflare"}}, "", ""},
		{"...while AkamaiGHost IS, because Akamai passes the origin's through",
			403, http.Header{"Server": {"AkamaiGHost"}}, "", "Akamai"},

		// The products the operator named, plus the rest of the
		// estate's likely front ends.
		{"Fastly's Next-Gen WAF by its agent header",
			403, http.Header{"X-Sigsci-Requestid": {"abc"}}, "",
			"Fastly (Signal Sciences)"},
		// Fastly's own block page is a customer-defined synthetic,
		// so there is nothing in the body to match and a
		// Fastly-fronted 403 without the agent header is not
		// claimed.
		{"a Fastly-fronted 403 with no decision header is not claimed",
			403, http.Header{"X-Served-By": {"cache-lhr-x"},
				"X-Timer": {"S123"}}, "<h1>Forbidden</h1>", ""},
		{"a CloudFront routing header on a 403 is not a block either",
			403, http.Header{"X-Cache": {"Error from cloudfront"},
				"X-Amz-Cf-Id": {"abc"}}, "<h1>Forbidden</h1>", ""},
		{"AWS WAF when it names its own action",
			403, http.Header{"X-Amzn-Waf-Action": {"block"}}, "", "AWS WAF"},
		{"Azure's WAF, which reads like an outage",
			403, nil,
			"<h2>Our services aren't available right now</h2>", "Azure WAF"},
		{"ModSecurity", 406, nil,
			"This error was generated by Mod_Security", "ModSecurity"},
		{"Fortinet", 403, nil, "<title>Web Page Blocked</title>",
			"Fortinet FortiWeb"},

		{"Imperva is recognised by its incident id",
			403, nil, "Incapsula incident ID: 123-456", "Imperva/Incapsula"},
		{"Akamai by its reference",
			403, nil, "Reference #18.1a2b3c4d", "Akamai"},
		{"F5 by its rejection wording",
			403, nil, "The requested URL was rejected. Support ID is: 99",
			"F5 BIG-IP ASM"},
		{"CloudFront's WAF sentence, whole",
			403, nil,
			"The request could not be satisfied. Request blocked. We can't",
			"AWS WAF"},
		// The near miss that matters: every CloudFront error page
		// says this, including a legitimate origin 403. The
		// takeover detector had to unlearn exactly this.
		{"a plain CloudFront error page is NOT a WAF block",
			403, nil,
			"<H2>The request could not be satisfied.</H2>Bad request." +
				"<PRE>Generated by cloudfront (CloudFront)</PRE>", ""},
	}
	for _, c := range cases {
		if got := Blocked(c.status, c.h, []byte(c.body)); got != c.want {
			t.Errorf("%s: Blocked() = %q, want %q", c.name, got, c.want)
		}
	}
}

func TestHeadersDoNotOverwriteTheProjectsUserAgent(t *testing.T) {
	// The attributable User-Agent is the whole reason the project
	// has one. A helper that silently replaced it would make an
	// engagement's traffic unattributable from the target's own
	// logs, which is the opposite of the house rule.
	h := http.Header{}
	h.Set("User-Agent", "OddJob/1.0 (+https://oddjob.dev)")
	Headers(h, ChromeUA)
	if got := h.Get("User-Agent"); got != "OddJob/1.0 (+https://oddjob.dev)" {
		t.Errorf("User-Agent was overwritten: %q", got)
	}
	if h.Get("Sec-Fetch-Mode") != "navigate" {
		t.Error("the rest of the browser headers were not added")
	}
	h2 := http.Header{}
	Headers(h2, "")
	if h2.Get("User-Agent") != ChromeUA {
		t.Errorf("empty ua did not fall back to Chrome: %q", h2.Get("User-Agent"))
	}
}

// The handshake is the feature, so it is tested against a real TLS
// server rather than asserted about. A unit test of "we called
// utls" would pass with the ALPN edit removed, which is the one
// line most likely to be wrong.
func tlsServer(t *testing.T, h http.HandlerFunc) (*httptest.Server, *[]string) {
	t.Helper()
	var seen []string
	srv := httptest.NewUnstartedServer(h)
	srv.TLS = &tls.Config{
		NextProtos: []string{"h2", "http/1.1"},
		GetConfigForClient: func(i *tls.ClientHelloInfo) (*tls.Config, error) {
			seen = append([]string(nil), i.SupportedProtos...)
			return nil, nil
		},
	}
	srv.StartTLS()
	t.Cleanup(srv.Close)
	return srv, &seen
}

func TestTransportCompletesARealHandshakeAndSpeaksHTTP11(t *testing.T) {
	srv, alpn := tlsServer(t, func(w http.ResponseWriter, r *http.Request) {
		_, _ = w.Write([]byte("proto=" + r.Proto)) //nolint:gosec // test server, r.Proto is net/http's own
	})

	cl := &http.Client{
		Timeout:   10 * time.Second,
		Transport: &Transport{InsecureSkipVerify: true},
	}
	res, err := cl.Get(srv.URL)
	if err != nil {
		t.Fatalf("handshake failed: %v", err)
	}
	defer func() { _ = res.Body.Close() }()
	buf := make([]byte, 64)
	n, _ := res.Body.Read(buf)
	if got := string(buf[:n]); !strings.Contains(got, "HTTP/1.1") {
		t.Errorf("not HTTP/1.1: %q", got)
	}
	// The ALPN narrowing, observed from the server's side. Without
	// the second BuildHandshakeState the edit is serialised too
	// late and "h2" is still offered.
	if len(*alpn) != 1 || (*alpn)[0] != "http/1.1" {
		t.Errorf("ALPN offered = %v, want [http/1.1]", *alpn)
	}
}

func TestTransportSendsChromesClientHelloNotGos(t *testing.T) {
	var chrome, plain *tls.ClientHelloInfo
	capture := func(dst **tls.ClientHelloInfo) func(*tls.ClientHelloInfo) (*tls.Config, error) {
		return func(i *tls.ClientHelloInfo) (*tls.Config, error) {
			c := *i
			*dst = &c
			return nil, nil
		}
	}

	run := func(cfgHook func(*tls.ClientHelloInfo) (*tls.Config, error),
		tr http.RoundTripper) {
		srv := httptest.NewUnstartedServer(http.HandlerFunc(
			func(w http.ResponseWriter, _ *http.Request) {
				_, _ = w.Write([]byte("ok"))
			}))
		srv.TLS = &tls.Config{GetConfigForClient: cfgHook}
		srv.StartTLS()
		defer srv.Close()
		cl := &http.Client{Timeout: 10 * time.Second, Transport: tr}
		res, err := cl.Get(srv.URL)
		if err != nil {
			t.Fatalf("get: %v", err)
		}
		_ = res.Body.Close()
	}

	run(capture(&chrome), &Transport{InsecureSkipVerify: true})
	run(capture(&plain), &http.Transport{
		TLSClientConfig: &tls.Config{InsecureSkipVerify: true}, //nolint:gosec // test
	})

	if chrome == nil || plain == nil {
		t.Fatal("did not capture both hellos")
	}
	// The cipher list IS the fingerprint, near enough: JA3 hashes
	// it in order. Identical lists would mean utls was not in the
	// path at all and this package does nothing.
	if sameInts(chrome.CipherSuites, plain.CipherSuites) {
		t.Error("the Chrome hello is byte-identical to Go's own: " +
			"utls is not in the handshake path")
	}
	// Chrome opens with a GREASE value, which Go never sends. This
	// is the single most load-bearing difference for a JA3 match.
	if len(chrome.CipherSuites) == 0 || !isGREASE(chrome.CipherSuites[0]) {
		t.Errorf("first cipher = %#x, want a GREASE value",
			firstOr(chrome.CipherSuites))
	}
}

func sameInts(a, b []uint16) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// GREASE values are 0x0a0a, 0x1a1a ... 0xfafa: both bytes equal, low
// nibble 0xa. Chrome sends one first; Go sends none at all.
func isGREASE(v uint16) bool {
	return v&0x0f0f == 0x0a0a && byte(v>>8) == byte(v&0xff)
}

func firstOr(v []uint16) uint16 {
	if len(v) == 0 {
		return 0
	}
	return v[0]
}

// The retry is the behaviour an operator actually sees, so it is
// tested end to end over real TLS: refuse the first request the way
// Cloudflare does, serve the page to the second.
func TestGetRetriesThroughTheBrowserOnlyWhenBlocked(t *testing.T) {
	var hits int
	srv, _ := tlsServer(t, func(w http.ResponseWriter, r *http.Request) {
		hits++
		if !strings.Contains(r.Header.Get("User-Agent"), "Chrome") {
			w.Header().Set("Cf-Ray", "8a1b2c3d4e5f6789-LHR")
			w.WriteHeader(http.StatusForbidden)
			_, _ = w.Write([]byte("Attention Required! | Cloudflare"))
			return
		}
		_, _ = w.Write([]byte("<html>the actual site</html>"))
	})

	f := &Fetcher{
		Plain: &http.Client{Timeout: 10 * time.Second,
			Transport: &http.Transport{
				TLSClientConfig: &tls.Config{InsecureSkipVerify: true}, //nolint:gosec // test
			}},
		Browser:   Client(10*time.Second, true),
		UserAgent: "OddJob/1.0 (+https://oddjob.dev)",
	}
	res, err := f.Get(context.Background(), srv.URL)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if res.BlockedBy != "Cloudflare" {
		t.Errorf("BlockedBy = %q, want Cloudflare", res.BlockedBy)
	}
	if !res.UsedBrowser {
		t.Error("did not retry through the browser handshake")
	}
	if res.StillBlocked {
		t.Error("reported still blocked after a successful retry")
	}
	if !strings.Contains(string(res.Body), "the actual site") {
		t.Errorf("body = %q", string(res.Body))
	}
	if hits != 2 {
		t.Errorf("made %d requests, want 2", hits)
	}
}

func TestGetDoesNotRetryAPlainForbidden(t *testing.T) {
	// A 403 nothing claims is the application's answer. Asking
	// again in a costume is a second request at a client for no
	// reason, and would turn a real boundary into a soft one.
	var hits int
	srv, _ := tlsServer(t, func(w http.ResponseWriter, _ *http.Request) {
		hits++
		w.WriteHeader(http.StatusForbidden)
		_, _ = w.Write([]byte("<h1>Forbidden</h1>"))
	})
	f := &Fetcher{
		Plain: &http.Client{Timeout: 10 * time.Second,
			Transport: &http.Transport{
				TLSClientConfig: &tls.Config{InsecureSkipVerify: true}, //nolint:gosec // test
			}},
		Browser: Client(10*time.Second, true),
	}
	res, err := f.Get(context.Background(), srv.URL)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if hits != 1 {
		t.Errorf("made %d requests, want 1", hits)
	}
	if res.UsedBrowser || res.BlockedBy != "" || res.StillBlocked {
		t.Errorf("treated a plain 403 as a block: %+v", res)
	}
}

func TestDisabledRecordsTheBlockWithoutRetrying(t *testing.T) {
	var hits int
	srv, _ := tlsServer(t, func(w http.ResponseWriter, _ *http.Request) {
		hits++
		w.Header().Set("Cf-Ray", "x")
		w.WriteHeader(http.StatusForbidden)
		_, _ = w.Write([]byte("blocked"))
	})
	f := &Fetcher{
		Plain: &http.Client{Timeout: 10 * time.Second,
			Transport: &http.Transport{
				TLSClientConfig: &tls.Config{InsecureSkipVerify: true}, //nolint:gosec // test
			}},
		Disabled: true,
	}
	res, err := f.Get(context.Background(), srv.URL)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if hits != 1 {
		t.Errorf("retried while disabled: %d requests", hits)
	}
	// Still SAID, which is the point: an operator who turned this
	// off should still learn the estate is filtering us.
	if res.BlockedBy != "Cloudflare" || !res.StillBlocked {
		t.Errorf("block was not recorded: %+v", res)
	}
}
