"""Recognise a bot filter's refusal as a refusal, not as the answer.

A WAF decides what you are before it decides what you asked for, and
the result is a 403 on a page a browser loads fine. Recorded as
`HTTP 403`, that reads as a fact about the client's application --
"this path refuses anonymous access" -- when it is a fact about our
HTTP stack. The same rule as everywhere else here: "found", "absent"
and "could not determine" are three answers, and a block page is the
third wearing the second's clothes.

**The twin of `ghost/internal/browserfetch/blocked.go`**, deliberately
and with the same markers, because the Ghost meets this on the client's
estate and the server meets it fetching assets. The vectors in
`backend/tests/assettest.py` and the table in the Go test are the same
cases, so the two cannot drift silently -- the same arrangement the
tunnel codec uses.

The Ghost can do something about it: it retries through a browser TLS
handshake. The server does not -- `httpx` sends Python's ClientHello
and nothing here changes that -- so this half only names the thing,
which is still the difference between a gap and a pass.
"""
from __future__ import annotations

#: A product's own wording on its block page, lowercased. Each is a
#: string the product puts there and a normal page does not carry.
BODY_MARKS: dict[str, tuple[str, ...]] = {
    "Cloudflare": (
        "attention required! | cloudflare",
        "cf-error-details",
        "checking your browser before accessing",
        "enable javascript and cookies to continue",
        "ray id:",
    ),
    "Akamai": (
        "reference #18.",
        "akamaighost",
        "access denied: you don't have permission to access",
    ),
    "Imperva/Incapsula": (
        "incapsula incident id",
        "powered by imperva",
        "_incapsula_resource",
    ),
    # The whole sentence, not "request blocked": two words appear on
    # any error page, and this exact string is already load-bearing
    # in `takeover.py`. "Generated by cloudfront" is deliberately NOT
    # here -- it is on EVERY CloudFront error page, including a
    # legitimate 403 from the origin, and treating that as a block
    # would hide a real access-control boundary. That is the mistake
    # the takeover detector had to unlearn.
    "AWS WAF": (
        "the request could not be satisfied. request blocked",
        # AWS WAF in front of an ALB rather than CloudFront.
        "<title>403 forbidden</title><hr>request blocked",
    ),
    "F5 BIG-IP ASM": (
        "the requested url was rejected",
        "support id is:",
    ),
    "Sucuri": (
        "sucuri website firewall",
        "access denied - sucuri website firewall",
    ),
    # Azure's WAF -- Front Door or Application Gateway -- serves this
    # wording, which reads like an outage and is not one.
    "Azure WAF": (
        "our services aren't available right now",
        "microsoft-azure-application-gateway",
        "the request is blocked",
    ),
    "ModSecurity": (
        "this error was generated by mod_security",
        "mod_security action",
        "<title>not acceptable!</title>",
    ),
    "Barracuda": (
        "you have been blocked by the barracuda",
        "barracuda web application firewall",
    ),
    "Radware": ("unusual activities from your computer",),
    "Fortinet FortiWeb": (
        "web application firewall has detected",
        "<title>web page blocked</title>",
    ),
    "Wallarm": ("blocked by wallarm",),
}

#: Headers the product sets regardless of how its page is branded.
#:
#: **Only headers that mean a decision was made.** A CDN's ordinary
#: routing headers are NOT here and must not be added: `x-cache` and
#: `x-amz-cf-id` (CloudFront), `x-served-by` and `x-timer` (Fastly),
#: `x-akamai-request-id`, `x-azure-ref` are on EVERY response those
#: networks serve, including a perfectly legitimate 403 from the
#: origin behind them. Keying on one would turn every access-control
#: boundary on a CDN-fronted estate into "blocked by the CDN", which
#: is the same error the takeover detector made with CloudFront and
#: is worse here -- it would excuse a finding rather than invent one.
HEADER_MARKS: dict[str, tuple[str, ...]] = {
    "Cloudflare": ("cf-ray", "cf-mitigated"),
    "Imperva/Incapsula": ("x-iinfo", "x-cdn"),
    "Sucuri": ("x-sucuri-id", "x-sucuri-block"),
    "F5 BIG-IP ASM": ("x-waf-event",),
    # Fastly's Next-Gen WAF (Signal Sciences). Fastly's own block
    # page is a customer-defined synthetic, so there is nothing
    # reliable to match in the body -- these headers are set by the
    # agent that made the decision, which is exactly the
    # distinction this table is drawn on. A Fastly-fronted 403
    # WITHOUT one of these is not claimed as a block.
    "Fastly (Signal Sciences)": (
        "x-sigsci-requestid", "x-sigsci-tags", "x-sigsci-agentresponse"),
    # AWS WAF names its own rule action in a header when the
    # distribution is configured to pass it through.
    "AWS WAF": ("x-amzn-waf-action",),
    "Akamai": ("x-akamai-session-info-deny",),
}

#: `Server:` values that name the product. The value carries it here,
#: not the key, which is why these are separate from HEADER_MARKS.
#:
#: `Server: AkamaiGHost` is the one CDN token that IS conclusive on a
#: refusing status: Akamai serves origin responses with the origin's
#: own Server header and only puts AkamaiGHost on a response it
#: generated itself. `Server: cloudflare`, by contrast, is on
#: everything Cloudflare proxies -- it is here because Cloudflare
#: strips it from nothing and a 403 it did not generate carries the
#: origin's body, which the body marks then fail to match, so the
#: pairing still needs a refusing status to fire. Kept, but it is the
#: weakest signal in this file.
SERVER_MARKS: dict[str, str] = {
    "akamaighost": "Akamai",
    "awselb": "AWS WAF",
    "big-ip": "F5 BIG-IP ASM",
    "sucuri": "Sucuri",
    "barracuda": "Barracuda",
}

#: Statuses a filter refuses with. A challenge comes back as 403, 429
#: or 503 depending on the mode, so keying on 403 alone would miss the
#: two that look most like the site being down.
#:
#: 401 and 402 are excluded on purpose: those are the server telling
#: us what to do next, which is information rather than interdiction.
REFUSING = (403, 406, 429, 503)


def blocked_by(status: int | None, headers=None, body: str | None = None
               ) -> str | None:
    """Which product refused this response, or None.

    **Status alone is never enough.** A 403 is the correct answer for
    a directory a tester is not allowed into, and calling that a WAF
    block would hide a real access-control boundary behind a
    plausible excuse. So a refusal has to be a refusing status AND a
    product that admits to it -- a header it set, or its own wording
    on the page.
    """
    if status not in REFUSING:
        return None
    if headers:
        # Case-insensitively, because httpx, requests and a raw
        # capture disagree about header case and this must not
        # depend on which one produced the row.
        low = {str(k).lower(): str(v) for k, v in dict(headers).items()}
        for name, keys in HEADER_MARKS.items():
            if any(low.get(k) for k in keys):
                return name
        server = low.get("server", "").lower()
        for token, name in SERVER_MARKS.items():
            if token in server:
                return name
    if not body:
        return None
    text = body.lower()
    for name, marks in BODY_MARKS.items():
        if any(m in text for m in marks):
            return name
    return None


def describe(status: int | None, who: str) -> str:
    """The sentence that goes where `HTTP 403` used to."""
    return (f"HTTP {status}: refused by {who}, not by the application. "
            f"The body is its block page. A Ghost can retry this through "
            f"a browser TLS handshake; this fetch runs on the server and "
            f"cannot.")
