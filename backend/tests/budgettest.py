"""Making a conversation fit the model that has to read it.

No server and no database: `app.agent.budget` is a pure function over
a message list, and the thing worth asserting is WHICH messages
survive, which a round trip through HTTP would only obscure.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from app.agent.budget import DROPPED, estimate, fit  # noqa: E402

passed = failed = 0


def check(label, cond, got=None):
    global passed, failed
    if cond:
        passed += 1
        print(f"  PASS  {label}" + (f" {got}" if got is not None else ""))
    else:
        failed += 1
        print(f"  FAIL  {label}" + (f" {got}" if got is not None else ""))


def convo(rounds: int, result_chars: int = 30000) -> list[dict]:
    """A thread shaped like a real one: ask, call a tool, answer."""
    out: list[dict] = []
    for i in range(rounds):
        out.append({"role": "user", "content": f"question {i}"})
        out.append({"role": "assistant", "content": "",
                    "tool_calls": [{"id": f"c{i}",
                                    "function": {"name": "list_vulns"}}]})
        out.append({"role": "tool", "tool_call_id": f"c{i}",
                    "content": "x" * result_chars})
        out.append({"role": "assistant", "content": f"answer {i}"})
    return out


print("== a thread that already fits is returned untouched ==")
small = convo(1, 100)
out, shed = fit(small, 100000)
check("nothing is dropped", shed == 0, shed)
check("...and the list is the same one", out == small)

print("\n== no budget means no limit ==")
# The default. A deployment that has not configured one must behave
# exactly as it did before this existed.
big = convo(10)
for nolimit in (0, -1):
    out, shed = fit(big, nolimit)
    check(f"budget {nolimit} changes nothing", out == big and shed == 0)

print("\n== over budget: tool results go, and the conversation stays ==")
# A budget that is achievable: ten results of 30k characters is about
# 100k tokens, and shedding the nine old ones leaves the newest one,
# which `fit` will not drop. Asking for less than that one result
# costs is the impossible case and is asserted separately below.
BUDGET = 20000
check("the thread starts over budget", estimate(big) > BUDGET, estimate(big))
out, shed = fit(big, BUDGET)
check("it now fits", estimate(out) <= BUDGET, estimate(out))
check("...and said how much it shed", shed > 0, shed)
# The rule that makes this safe: a tool result can be regenerated by
# calling the tool again, and what a person asked cannot be recovered
# from anywhere.
kept_user = [m["content"] for m in out if m.get("role") == "user"]
check("every question a person asked survives",
      kept_user == [f"question {i}" for i in range(10)], kept_user[:3])
kept_answers = [m["content"] for m in out
                if m.get("role") == "assistant" and m.get("content")]
check("...and every answer the model gave",
      len(kept_answers) == 10, len(kept_answers))

print("\n== a dropped result says so, and names its tool ==")
holes = [m for m in out if m.get("role") == "tool"
         and m["content"].startswith("[")]
check("the gap is marked rather than left blank", holes, len(holes))
check("...and names the tool to call again",
      all("list_vulns" in m["content"] for m in holes),
      holes[0]["content"][:70] if holes else None)
check("...which is what DROPPED promises", "{tool}" in DROPPED)

print("\n== the newest exchange is never touched ==")
# A request trimmed past the question being asked has nothing worth
# sending, so the last user message and everything after it is kept
# whatever the budget says -- EVEN WHEN THAT MEANS STILL BEING OVER.
# Returning something that cannot answer the question would turn a
# clear 400 into a confident wrong answer, which is worse.
out, _ = fit(big, 500)
check("the last question is still there", "question 9" in str(out))
_last_tool = [m for m in out
              if m.get("role") == "tool" and m.get("tool_call_id") == "c9"]
check("...and so is the tool result from that exchange",
      _last_tool and not _last_tool[0]["content"].startswith("["),
      _last_tool[0]["content"][:20] if _last_tool else None)
check("...so an impossible budget is honestly still over it",
      estimate(out) > 500, estimate(out))

print("\n== an impossible budget sheds whole exchanges, oldest first ==")
# Small results, so the last exchange is not itself the problem and
# the only way down is to drop older rounds entirely.
out, _ = fit(convo(6, 200), 60)
asked = [m["content"] for m in out if m.get("role") == "user"]
check("the oldest questions are the ones that go",
      asked and asked[-1] == "question 5", asked)
check("...and fewer remain than went in", len(asked) < 6, len(asked))
check("...and it never empties the list", len(out) > 0, len(out))

print("\n== the estimate counts what goes on the wire ==")
# Structured content is serialised to JSON by the provider, so that
# is what it costs -- not `len(str(...))` of a Python repr.
_structured = [{"role": "assistant", "content": [{"type": "text",
                                                  "text": "y" * 3000}]}]
check("structured content is counted, not skipped",
      estimate(_structured) > 900, estimate(_structured))
check("a system prompt counts too",
      estimate([], "z" * 3000) > 900, estimate([], "z" * 3000))
check("tool_calls beside the content count",
      estimate([{"role": "assistant", "content": "",
                 "tool_calls": [{"id": "c", "function": {"name": "x" * 3000}}]}])
      > 900)

print(f"\n{passed} passed, {failed} failed")
sys.exit(1 if failed else 0)
